<script>
    function openTab(evt, tabName) {
        var i, tabcontent, tablinks;
        tabcontent = document.getElementsByClassName("tabcontent");
        for (i = 0; i < tabcontent.length; i++) tabcontent[i].style.display = "none";
        tablinks = document.getElementsByClassName("tablinks");
        for (i = 0; i < tablinks.length; i++) tablinks[i].className = tablinks[i].className.replace(" active", "");
        document.getElementById(tabName).style.display = "block";
        evt.currentTarget.className += " active";
    }

    const positions = <?php echo $positions_json; ?>;
    const currentPosId = <?php echo $character['position_id'] ?: 'null'; ?>;
    
    function updatePositions(selectedPosId = null) {
        const deptSelect = document.getElementById('dept_select');
        const posSelect = document.getElementById('pos_select');
        posSelect.innerHTML = '<option value="">-- Select Position --</option>';
        positions.forEach(pos => {
            if (pos.department_id == deptSelect.value) {
                const option = document.createElement('option');
                option.value = pos.id;
                option.textContent = pos.name;
                if (selectedPosId && pos.id == selectedPosId) option.selected = true;
                posSelect.appendChild(option);
            }
        });
    }
    window.onload = function() { if (document.getElementById('dept_select').value !== "") updatePositions(currentPosId); };
</script>

