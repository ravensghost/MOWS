require_once 'auth.php';
$user_id = $current_user['id']; // $current_user is automatically generated by auth.php

$success = '';
$error = '';
$char_id = isset($_GET['id']) ? (int)$_GET['id'] : 0;

if (!$char_id) die("Error: No character ID specified.");

$stmt = $pdo->prepare("SELECT * FROM characters WHERE id = ?");
$stmt->execute([$char_id]);
$character = $stmt->fetch(PDO::FETCH_ASSOC);

if (!$character) die("Error: Character not found.");

$is_admin = in_array($_SESSION['role'], ['admin', 'system_admin']);
if ($character['user_id'] !== $_SESSION['user_id'] && !$is_admin) {
    die("Access Denied: You do not have permission to edit this character.");
}

$schema_stmt = $pdo->prepare("SELECT * FROM system_form_schemas WHERE form_target = 'characters' ORDER BY tab_name ASC, sort_order ASC");
$schema_stmt->execute();
$schema_fields = $schema_stmt->fetchAll(PDO::FETCH_ASSOC);

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $char_name = trim($_POST['char_name']);
    $dept_id = $_POST['department_id'] ?: null;
    $pos_id = $_POST['position_id'] ?: null;
    $avatar = $character['avatar']; // Default to existing

    // Handle Image Upload
    if (isset($_FILES['avatar_file']) && $_FILES['avatar_file']['error'] === UPLOAD_ERR_OK) {
        $allowed_exts = ['jpg', 'jpeg', 'png', 'gif'];
        $ext = strtolower(pathinfo($_FILES['avatar_file']['name'], PATHINFO_EXTENSION));
        
        if (in_array($ext, $allowed_exts)) {
            $new_avatar = uniqid('av_') . '.' . $ext;
            $dest = 'uploads/avatars/' . $new_avatar;
            if (move_uploaded_file($_FILES['avatar_file']['tmp_name'], $dest)) {
                $avatar = $new_avatar;
            }
        } else {
            $error = "Invalid image format. Only JPG, PNG, and GIF are allowed.";
        }
    }

    $dynamic_data = [];
    foreach ($schema_fields as $field) {
        $key = $field['field_key'];
        if (isset($_POST[$key])) $dynamic_data[$key] = trim($_POST[$key]);
    }
    $json_data = json_encode($dynamic_data);

    if (!$error) {
        try {
            $update_stmt = $pdo->prepare("UPDATE characters SET name = ?, department_id = ?, position_id = ?, avatar = ?, dynamic_data = ? WHERE id = ?");
            $update_stmt->execute([$char_name, $dept_id, $pos_id, $avatar, $json_data, $char_id]);
            $success = "Service Record updated successfully!";
            
            $stmt->execute([$char_id]);
            $character = $stmt->fetch(PDO::FETCH_ASSOC);
        } catch (PDOException $e) {
            $error = "An error occurred while updating the character.";
        }
    }
}

$existing_dynamic_data = json_decode($character['dynamic_data'], true) ?: [];
$departments = $pdo->query("SELECT id, name FROM departments ORDER BY sort_order ASC")->fetchAll();
$positions_json = json_encode($pdo->query("SELECT id, department_id, name FROM positions ORDER BY sort_order ASC")->fetchAll());

$dynamic_tabs = [];
foreach ($schema_fields as $field) {
    $dynamic_tabs[$field['tab_name']][] = $field;
}
